/** Pick honest variant widths: standard steps that fit the source, plus the
 * native width when it is meaningfully larger than the biggest step. */
function pickWidths(sourceWidth) {
  const chosen = STANDARD_WIDTHS.filter((w) => w <= sourceWidth);
  if (chosen.length === 0) return [sourceWidth];
  const largest = chosen[chosen.length - 1];
  if (sourceWidth > largest * 1.15 && sourceWidth < STANDARD_WIDTHS[STANDARD_WIDTHS.length - 1]) {
    chosen.push(sourceWidth);
  }
  return chosen;
}

async function emitVariants(input, outBase, key, manifest) {
  const meta = await sharp(input).metadata();
  const widths = pickWidths(meta.width);
  const parts = [];
  await mkdir(path.dirname(path.join(PUBLIC, outBase)), { recursive: true });
  for (const w of widths) {
    const outRel = `${outBase}.w${w}.webp`;
    const out = path.join(PUBLIC, outRel);
    const info = await sharp(input).resize({ width: w }).webp({ quality: QUALITY }).toFile(out);
    parts.push(`/${outRel} ${w}w`);
    console.log(`  ${outRel}  ${info.width}x${info.height}  ${(info.size / 1024).toFixed(0)}KB`);
  }
  manifest[key] = parts.join(", ");
}

const manifest = {};

for (const rel of LOCAL) {
  console.log(rel);
  const base = rel.replace(/\.(png|jpe?g|webp)$/i, "");
  await emitVariants(path.join(PUBLIC, rel), base, `/${rel}`, manifest);
}

for (const [url, outBase] of REMOTE) {
  console.log(url);
  const res = await fetch(`http://localhost:8080${url}`);
  if (!res.ok) throw new Error(`fetch failed ${res.status} for ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await emitVariants(buf, outBase, url, manifest);
}

const ts = `// AUTO-GENERATED by scripts/optimize-landing-images.mjs — do not edit by hand.
// Maps a landing image src (exactly as components reference it) to a WebP
// srcset string. Regenerate after adding/replacing landing images.
export const LANDING_IMAGE_SRCSET: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;
await writeFile(path.join(ROOT, "src/lib/landing-image-manifest.ts"), ts);
