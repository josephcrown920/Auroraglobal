// One-time (re-runnable) landing image optimizer — task: convert landing images
// to WebP and generate responsive srcset variants.
//
// For every listed image it emits `<base>.w<width>.webp` siblings next to the
// original inside public/, then regenerates src/lib/landing-image-manifest.ts
// mapping the ORIGINAL src (exactly as components reference it) to a webp
// srcset string. Components render the originals as <img> fallback, so a
// missing variant can never break the page.
//
// Remote entries are workspace assets served by the dev server; they are
// downloaded from http://localhost:8080 (dev server must be running) and the
// webp variants land in public/josh/slideshow/.
//
// Usage: node scripts/optimize-landing-images.mjs
import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const STANDARD_WIDTHS = [480, 960, 1440];
const QUALITY = 82;

